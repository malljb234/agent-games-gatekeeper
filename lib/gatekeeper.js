function decodeHexLoose(s) {
  const t = String(s || "").trim().replace(/^0x/i, "");
  if (!t || t.length % 2 !== 0 || !/^[0-9a-fA-F]+$/.test(t)) return null;
  try {
    return Buffer.from(t, "hex");
  } catch {
    return null;
  }
}
function decodeBase64Loose(s, urlSafe) {
  let t = String(s || "").trim();
  if (urlSafe) t = t.replace(/-/g, "+").replace(/_/g, "/");
  if (!t || !/^[A-Za-z0-9+/]+={0,2}$/.test(t)) return null;
  // ROUND 2 fix: accept UNPADDED base64/base64url (a 32-byte secret
  // encodes to 43 chars without padding) by padding to a multiple of 4.
  // A body length % 4 === 1 can never be valid base64 — reject it.
  const bodyLen = t.replace(/=+$/, "").length;
  if (bodyLen % 4 === 1) return null;
  t += "=".repeat((4 - (t.length % 4)) % 4);
  try {
    const b = Buffer.from(t, "base64");
    return b.length > 0 ? b : null;
  } catch {
    return null;
  }
}

// Canonical JSON: object keys sorted recursively, compact, no whitespace.
// (JSON.stringify keeps insertion order, so a platform that signs the
// canonical form will not match a raw body whose keys arrive in a
// different order or with different spacing.)
function canonicalJson(value) {
  if (value === null || typeof value !== "object") return JSON.stringify(value);
  if (Array.isArray(value)) return "[" + value.map(canonicalJson).join(",") + "]";
  const keys = Object.keys(value).sort();
  return (
    "{" +
    keys.map((k) => JSON.stringify(k) + ":" + canonicalJson(value[k])).join(",") +
    "}"
  );
}

// Every way the platform's 32-byte secret could be turned into an HMAC
// key from the string the dashboard shows (and the env var holds).
// NOTE (round 2): "hex-decoded" is correctly ABSENT when the secret is
// not a hex string — decodeHexLoose returns null for non-hex input, and
// the live log proved the secret is base64 (it decoded as base64, so it
// contains a non-hex character). That is not a pruning bug.
// ROUND 3: `env` is the parsed envelope (may be empty). Its agent_id is
// the platform's own agent UUID from the preflight body — NOT our agent
// name/handle. Key derivations that bind the agent id, the literal
// "agent-games", string-form digests, re-encodings and case variants
// are all tried (each still requires the secret itself).
function candidateKeys(secretStr, env) {
  const keys = [];
  const seen = new Set();
  const push = (buf, label) => {
    if (!buf || buf.length === 0) return;
    const id = buf.toString("hex");
    if (seen.has(id)) return;
    seen.add(id);
    keys.push({ buf, label });
  };
  push(Buffer.from(secretStr, "utf8"), "raw-string");
  const hex = decodeHexLoose(secretStr);
  push(hex, "hex-decoded");
  const b64 = decodeBase64Loose(secretStr, false);
  push(b64, "base64-decoded");
  push(decodeBase64Loose(secretStr, true), "base64url-decoded");
  // Some platforms hash the displayed secret before using it as the key.
  const shaOfSecret = crypto.createHash("sha256").update(secretStr, "utf8").digest();
  push(shaOfSecret, "sha256-of-secret");
  if (b64) {
    push(crypto.createHash("sha256").update(b64).digest(), "sha256-of-decoded-key");
  }
  if (hex) {
    push(crypto.createHash("sha256").update(hex).digest(), "sha256-of-hex-key");
  }
  // ROUND 3 — the sha256 digest itself, used as a STRING key (hex /
  // base64 / base64url text), and the decoded key bytes re-encoded to
  // text and used as a string key. The live log's tried_keys included
  // "sha256(raw) hex", "sha256(raw) b64" and "b64url(sha256(raw))" —
  // those are string-form keys, not raw digest bytes.
  push(Buffer.from(shaOfSecret.toString("hex"), "utf8"), "sha256hex-string-key");
  push(Buffer.from(shaOfSecret.toString("base64"), "utf8"), "sha256b64-string-key");
  push(Buffer.from(shaOfSecret.toString("base64url"), "utf8"), "sha256b64url-string-key");
  if (b64) {
    push(Buffer.from(b64.toString("base64"), "utf8"), "b64-of-decoded-key-string");
    push(Buffer.from(b64.toString("base64url"), "utf8"), "b64url-of-decoded-key-string");
    push(Buffer.from(b64.toString("hex"), "utf8"), "hex-of-decoded-key-string");
  }
  // ROUND 3 — case variants of the displayed secret (matters only if
  // the secret is hex-like; dedupe drops the no-op copies).
  const lower = String(secretStr).toLowerCase();
  const upper = String(secretStr).toUpperCase();
  if (lower !== secretStr) push(Buffer.from(lower, "utf8"), "secret-lowercase");
  if (upper !== secretStr) push(Buffer.from(upper, "utf8"), "secret-uppercase");
  // ROUND 3 — agent-id-bound derivations. The ids are the agent_id UUID
  // from the envelope body first, then our own agent name / owner handle.
  const ids = [];
  if (env && env.agent_id) ids.push(String(env.agent_id));
  for (const id of AGENT_IDS) if (!ids.includes(id)) ids.push(id);
  const decodedForms = [];
  if (b64) decodedForms.push(b64);
  if (hex) decodedForms.push(hex);
  for (const id of ids) {
    const tag = id === (env && env.agent_id) ? ":body" : ":" + id;
    push(crypto.createHash("sha256").update(secretStr + id, "utf8").digest(), "sha256(secret+agentid)" + tag);
    push(crypto.createHash("sha256").update(id + secretStr, "utf8").digest(), "sha256(agentid+secret)" + tag);
    push(crypto.createHmac("sha256", secretStr).update(id, "utf8").digest(), "hmac(secret,agentid)" + tag);
    for (const dec of decodedForms) {
      push(crypto.createHash("sha256").update(Buffer.concat([dec, Buffer.from(id, "utf8")])).digest(), "sha256(decoded+agentid)" + tag);
      push(crypto.createHash("sha256").update(Buffer.concat([Buffer.from(id, "utf8"), dec])).digest(), "sha256(agentid+decoded)" + tag);
      push(crypto.createHmac("sha256", dec).update(id, "utf8").digest(), "hmac(decoded,agentid)" + tag);
    }
  }
  // ROUND 3 — the literal "agent-games" bound into the key.
  push(crypto.createHash("sha256").update(secretStr + "agent-games", "utf8").digest(), "sha256(secret+agent-games)");
  if (b64) {
    push(crypto.createHash("sha256").update(Buffer.concat([b64, Buffer.from("agent-games", "utf8")])).digest(), "sha256(decoded+agent-games)");
  }
  return keys;
}

// Every way the platform's signature value could be encoded.
function candidateSignatures(provided) {
  const s = String(provided || "")
    .trim()
    .replace(/^(sha256|hmac-sha256|sha-256)=/i, "")
    .trim();
  const out = [];
  const seen = new Set();
  const push = (buf, label) => {
    if (!buf || buf.length === 0) return;
    const id = buf.toString("hex");
    if (seen.has(id)) return;
    seen.add(id);
    out.push({ buf, label });
  };
  push(decodeHexLoose(s), "hex");
  push(decodeBase64Loose(s, false), "base64");
  push(decodeBase64Loose(s, true), "base64url");
  return out;
}

