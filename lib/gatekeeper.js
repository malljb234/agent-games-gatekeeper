function fieldFromHashHex(hex) {
  // First 31 bytes of a hash as a BN254 field element (always < Fr).
  return BigInt("0x" + hex.slice(0, 62)).toString(10);
}
function sha256hex(data) {
  return crypto.createHash("sha256").update(data).digest("hex");
}
function hmacHex(secret, data) {
  return crypto.createHmac("sha256", secret).update(data).digest("hex");
}

// ROUND 3: the platform's signature is 64 chars. HMAC-SHA-256 hex is
// 64 chars, but so is HMAC-SHA-384 base64 (48 bytes -> exactly 64
// base64 chars, no padding) and HMAC-SHA-512/256 hex (32 bytes).
// Try every plausible hash; "-trunc32" truncates a longer digest to
// its first 32 bytes (hex 64).
const HASH_ALGORITHMS = ["sha256", "sha384", "sha384-trunc32", "sha512-256", "sha512-trunc32"];
function hmacDigest(algo, keyBuf, payloadBuf) {
  if (algo === "sha384-trunc32") {
    return crypto.createHmac("sha384", keyBuf).update(payloadBuf).digest().subarray(0, 32);
  }
  if (algo === "sha512-trunc32") {
    return crypto.createHmac("sha512", keyBuf).update(payloadBuf).digest().subarray(0, 32);
  }
  return crypto.createHmac(algo, keyBuf).update(payloadBuf).digest();
}
function encodeDigest(digestBuf, encoding) {
  if (encoding === "base64") return digestBuf.toString("base64");
  if (encoding === "base64url") return digestBuf.toString("base64url");
  return digestBuf.toString("hex");
}

