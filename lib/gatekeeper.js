// The signed payload: the raw body first, then every other plausible
// construction. Timestamp-mixed variants come from a timestamp HEADER
// (Stripe-style `timestamp.body`) OR from a timestamp field inside the
// envelope body (the /build guide says "the task signature and timestamp
// are valid" but pins no header, so the timestamp may be in the body).
// ROUND 3: `env` is the parsed envelope. Its own fields (type,
// agent_id, issued_at, nonce) are now payload material: each field
// alone, pairs/triples with several separators, and the envelope
// WITHOUT the type field. The preflight body is 171 bytes and carries
// no `input` object, so input-* payloads do not apply to it.
// Dedupe is by CONTENT (ROUND 3): an identical construction is never
// computed twice under two different labels.
function candidatePayloads(headers, rawBody, env) {
  const payloads = [];
  const seen = new Set();
  const push = (buf, label) => {
    if (!buf || buf.length === 0) return;
    const id = buf.toString("hex");
    if (seen.has(id)) return;
    seen.add(id);
    payloads.push({ buf, label });
  };
  const B = (...parts) =>
    Buffer.concat(
      parts.map((p) => (Buffer.isBuffer(p) ? p : Buffer.from(String(p), "utf8")))
    );
  const raw = Buffer.from(rawBody);
  push(raw, "raw-body");

  // JSON re-serialisations of the parsed body.
  let parsed = null;
  try {
    parsed = JSON.parse(raw.toString("utf8"));
  } catch {
    parsed = null;
  }
  if (parsed !== null && parsed !== undefined) {
    push(B(canonicalJson(parsed)), "canonical-json");
    push(B(JSON.stringify(parsed)), "restringified-json");
    push(B(JSON.stringify(parsed, null, 2)), "pretty-json");
    if (parsed && typeof parsed === "object" && parsed.input && typeof parsed.input === "object") {
      push(B(canonicalJson(parsed.input)), "input-canonical-json");
      push(B(JSON.stringify(parsed.input)), "input-json");
    }
    // HMAC over the body's digest instead of the body itself.
    const digest = crypto.createHash("sha256").update(raw).digest();
    push(B(digest.toString("hex")), "sha256hex-body");
    push(digest, "sha256raw-body");
    // Timestamp fields inside the envelope body.
    const tsFields = [
      "timestamp",
      "ts",
      "issued_at",
      "issuedAt",
      "time",
      "created_at",
      "deadline_at",
    ];
    for (const f of tsFields) {
      const v = parsed[f];
      if (v === undefined || v === null || v === "") continue;
      const ts = Buffer.from(String(v), "utf8");
      push(B(ts, ".", raw), "body-ts.body:" + f);
      push(B(ts, raw), "body-ts+body:" + f);
    }
    // ROUND 3 — payloads built from the envelope's own fields. The
    // preflight envelope is {type, agent_id, issued_at, nonce}; the
    // platform may sign a field, a field combination, or the envelope
    // minus one field instead of the whole body.
    const field = (name) => {
      const v = parsed[name];
      return v === undefined || v === null || v === "" ? null : String(v);
    };
    const type = field("type");
    const agentId = field("agent_id");
    const nonce = field("nonce");
    const issuedAt = field("issued_at");
    // Each field alone.
    if (type) push(B(type), "type-only");
    if (agentId) push(B(agentId), "agentid-only");
    if (nonce) push(B(nonce), "nonce-only");
    if (issuedAt) push(B(issuedAt), "issuedat-only");
    // Field pairs / triples, several separators ("", ".", ":", "|", "\n").
    const SEPS = ["", ".", ":", "|", "\n"];
    const join = (sep, ...parts) => parts.join(sep);
    if (type && nonce) {
      for (const s of SEPS) push(B(join(s, type, nonce)), "type+nonce:" + JSON.stringify(s));
    }
    if (agentId && nonce) {
      for (const s of SEPS) {
        push(B(join(s, agentId, nonce)), "agentid+nonce:" + JSON.stringify(s));
        push(B(join(s, nonce, agentId)), "nonce+agentid:" + JSON.stringify(s));
      }
    }
    if (type && issuedAt && nonce) {
      for (const s of SEPS) push(B(join(s, type, issuedAt, nonce)), "type+issuedat+nonce:" + JSON.stringify(s));
    }
    if (type && agentId && nonce) {
      for (const s of SEPS) push(B(join(s, type, agentId, nonce)), "type+agentid+nonce:" + JSON.stringify(s));
    }
    // The envelope WITHOUT the type field (canonical sorted keys, and
    // the sent-order re-stringification).
    if (parsed && typeof parsed === "object" && type) {
      const noType = { ...parsed };
      delete noType.type;
      push(B(canonicalJson(noType)), "no-type-canonical-json");
      push(B(JSON.stringify(noType)), "no-type-json");
    }
    // ROUND 3 — the BODY agent_id UUID as prefix/suffix (round 2 only
    // used our agent name / owner handle here).
    if (agentId) {
      push(B(agentId, raw), "body-agentid+body");
      push(B(raw, agentId), "body+body-agentid");
      push(B(agentId, ".", raw), "body-agentid.dot-body");
      push(B(agentId, "\n", raw), "body-agentid-newline-body");
      push(B(agentId, ":", raw), "body-agentid:body");
      push(B(agentId, "|", raw), "body-agentid|body");
      if (nonce) {
        push(B(agentId, nonce, raw), "body-agentid+nonce+body");
        push(B(nonce, agentId, raw), "nonce+body-agentid+body");
        push(B(raw, agentId, nonce), "body+body-agentid+nonce");
        push(B(raw, nonce, agentId), "body+nonce+body-agentid");
      }
    }
  }

  // Trailing-newline variants.
  push(B(raw.toString("utf8").replace(/[\r\n]+$/, "")), "body-trimmed");
  push(B(raw, "\n"), "body+newline");

  // Request-line style: method and/or path mixed into the payload.
  for (const p of ENDPOINT_PATHS) {
    push(B("POST\n", p, "\n", raw), "method-path-body:" + p);
    push(B("POST ", p, "\n", raw), "method-space-path-body:" + p);
    push(B(p, raw), "path+body:" + p);
    push(B(p, "\n", raw), "path-newline-body:" + p);
  }
  push(B("POST\n", raw), "method-newline-body");
  push(B("POST", raw), "method+body");

  // Agent-id binding (prefix / suffix / separators).
  for (const id of AGENT_IDS) {
    push(B(id, raw), "agentid+body:" + id);
    push(B(raw, id), "body+agentid:" + id);
    push(B(id, ".", raw), "agentid-dot-body:" + id);
    push(B(id, "\n", raw), "agentid-newline-body:" + id);
  }

  // Full endpoint URL binding.
  push(B(ENDPOINT_URL, raw), "endpoint-url+body");
  push(B(ENDPOINT_URL, "\n", raw), "endpoint-url-newline-body");

  // Timestamp-header variants (round 1; only when a header is present).
  for (const name of TIMESTAMP_HEADER_NAMES) {
    const ts = headers[name];
    if (ts === undefined || ts === "") continue;
    const tsBuf = Buffer.from(String(ts), "utf8");
    push(B(tsBuf, ".", raw), "timestamp.body:" + name);
    push(B(tsBuf, raw), "timestamp+body:" + name);
  }
  return payloads;
}

// The key derivation that matched the last verified request, plus the
// secret string it was derived from, the HMAC hash and the signature
// encoding that matched. Responses are signed with the SAME key, hash
// and encoding (the platform verifies responses with the same scheme it
// signs with); they reset automatically when the configured secret
// changes.
let responseKey = null;
let responseKeySecret = null;
let responseHash = "sha256";
let responseSigEncoding = "hex";

// Returns { key, sig, payload, hash, header } labels on match, null
// otherwise. Logs only labels and metadata — never the secret, any
// signature value, or any key bytes.
// ROUND 3: EVERY present signature header is tried (the preflight
// carries BOTH x-agent-games-signature AND a separate "signature"
// header), and EVERY (key, payload) pair is tried under EVERY hash in
// HASH_ALGORITHMS. Accept if ANY combination matches.
function verifyIncomingHmac(headers, rawBody) {
  const secretStr = hmacSecret();
  let parsed = null;
  try {
    parsed = JSON.parse(rawBody.toString("utf8"));
  } catch {
    parsed = null;
  }
  const env = parsed && typeof parsed === "object" ? parsed : {};
  const keys = candidateKeys(secretStr, env);
  const payloads = candidatePayloads(headers, rawBody, env);
  // All signature headers present on the request, in priority order.
  // (Round 1–2 stopped at the first one found and never tried the
  // "signature" header the preflight also carries.)
  const sigHeaders = [];
  for (const name of SIG_HEADER_NAMES) {
    if (headers[name]) {
      const value = String(headers[name]);
      sigHeaders.push({ name, value, sigs: candidateSignatures(value) });
    }
  }
  for (const key of keys) {
    for (const payload of payloads) {
      for (const algo of HASH_ALGORITHMS) {
        const expected = hmacDigest(algo, key.buf, payload.buf);
        for (const sh of sigHeaders) {
          for (const sig of sh.sigs) {
            if (
              sig.buf.length === expected.length &&
              crypto.timingSafeEqual(sig.buf, expected)
            ) {
              responseKey = key.buf;
              responseKeySecret = secretStr;
              responseHash = algo;
              responseSigEncoding = sig.label;
              return {
                key: key.label,
                sig: sig.label,
                payload: payload.label,
                hash: algo,
                header: sh.name,
              };
            }
          }
        }
      }
    }
  }
  const bodyText = rawBody.toString("utf8");
  const firstHeader = sigHeaders[0];
  console.error(
    "hmac mismatch: sig_header=" +
      (firstHeader ? firstHeader.name : "(none)") +
      " sig_len=" +
      (firstHeader ? firstHeader.value.length : 0) +
      " sig_formats=[" +
      (firstHeader ? firstHeader.sigs.map((s) => s.label).join(",") : "") +
      "] sig_headers=[" +
      sigHeaders
        .map(
          (sh) =>
            sh.name +
            ":len=" +
            sh.value.length +
            ":formats=[" +
            sh.sigs.map((s) => s.label).join(",") +
            "]"
        )
        .join(",") +
      "] hash_algos=[" +
      HASH_ALGORITHMS.join(",") +
      "] headers=[" +
      Object.keys(headers).join(",") +
      "] body_len=" +
      rawBody.length +
      " body_sha256=" +
      sha256hex(rawBody) +
      " body=" +
      bodyText.slice(0, 2000) +
      (bodyText.length > 2000 ? "...(truncated)" : "") +
      " tried_keys=[" +
      keys.map((k) => k.label).join(",") +
      "] tried_payloads=[" +
      payloads.map((p) => p.label).join(",") +
      "]"
  );
  return null;
}
function normAddr(a) {
  return String(a || "").toLowerCase();
}
function normHash(h) {
  return String(h || "").toLowerCase();
}
function toBigIntLoose(v) {
  // Accept decimal strings, hex strings, or numbers.
  if (typeof v === "number") return BigInt(v);
  const s = String(v).trim();
  return s.startsWith("0x") || s.startsWith("0X") ? BigInt(s) : BigInt(s);
}

// ---------------------------------------------------------------------------
// Decision checklist (official trap encyclopedia, 7 varieties).
// Returns { decision: "APPROVE"|"REJECT", reason_code }.
// ---------------------------------------------------------------------------
function decide(input) {
  const proofTx = normHash(input.proof_tx || input.proofTx || "");
  if (proofTx && seenProofTx.has(proofTx)) {
    return { decision: "REJECT", reason_code: "PROOF_REUSED", proofTx };
  }
  const registeredVk = normHash(input.registered_vk || input.registeredVk || "");
  const proofVk = normHash(input.proof_vk || input.proofVk || "");
  if (
    !registeredVk ||
    !proofVk ||
    registeredVk !== proofVk ||
    registeredVk !== REGISTERED_VK_HASH
  ) {
    return { decision: "REJECT", reason_code: "VK_SUBSTITUTION", proofTx };
  }
  let minimum, publicBalance, expiryBlock, currentBlock, amount, maxTransfer;
  try {
    minimum = toBigIntLoose(input.minimum);
    publicBalance = toBigIntLoose(input.public_balance ?? input.publicBalance);
    expiryBlock = toBigIntLoose(input.expiry_block ?? input.expiryBlock);
    currentBlock = toBigIntLoose(input.current_block ?? input.currentBlock);
    amount = toBigIntLoose(input.amount);
    maxTransfer = toBigIntLoose(input.max_transfer ?? input.maxTransfer);
  } catch {
    return { decision: "REJECT", reason_code: "INVALID_TASK", proofTx };
  }
  if (publicBalance < minimum) {
    return { decision: "REJECT", reason_code: "THRESHOLD_MISMATCH", proofTx };
  }
  if (expiryBlock <= currentBlock) {
    return { decision: "REJECT", reason_code: "EXPIRED_CONDITION", proofTx };
  }
  if (normAddr(input.recipient) !== normAddr(input.condition_recipient || input.conditionRecipient)) {
    return { decision: "REJECT", reason_code: "RECIPIENT_MISMATCH", proofTx };
  }
  if (amount > maxTransfer) {
    return { decision: "REJECT", reason_code: "AMOUNT_OVERFLOW", proofTx };
  }
  return { decision: "APPROVE", reason_code: "VALID_CONDITION", proofTx };
}

// ---------------------------------------------------------------------------
// Groth16 proof of the decision with the official circuit.
// Circuit signals (verified locally against the official wasm/zkey):
//   registeredVkHash, proofVkHash, minimum, publicBalance, expiryBlock,
//   currentBlock, recipient, conditionRecipient, amount, maxTransfer,
//   decision, taskId, salt   (13 public signals)
// ---------------------------------------------------------------------------
async function proveDecision(input, decision) {
  const secret = hmacSecret();
  const taskId = String(input.task_id || input.taskId || "");
  const circuitInput = {
    registeredVkHash: toBigIntLoose(input.registered_vk || input.registeredVk).toString(10),
    proofVkHash: toBigIntLoose(input.proof_vk || input.proofVk).toString(10),
    minimum: toBigIntLoose(input.minimum).toString(10),
    publicBalance: toBigIntLoose(input.public_balance ?? input.publicBalance).toString(10),
    expiryBlock: toBigIntLoose(input.expiry_block ?? input.expiryBlock).toString(10),
    currentBlock: toBigIntLoose(input.current_block ?? input.currentBlock).toString(10),
    recipient: toBigIntLoose(input.recipient).toString(10),
    conditionRecipient: toBigIntLoose(
      input.condition_recipient || input.conditionRecipient
    ).toString(10),
    amount: toBigIntLoose(input.amount).toString(10),
    maxTransfer: toBigIntLoose(input.max_transfer ?? input.maxTransfer).toString(10),
    decision: decision === "APPROVE" ? "1" : "0",
    taskId: fieldFromHashHex(sha256hex(taskId || "no-task-id")),
    salt: secret
      ? fieldFromHashHex(hmacHex(secret, taskId || "no-task-id"))
      : fieldFromHashHex(sha256hex("salt:" + taskId)),
  };
  const { proof, publicSignals } = await snarkjs.groth16.fullProve(
    circuitInput,
    WASM,
    ZKEY
  );
  return { proof, publicSignals };
}

// ---------------------------------------------------------------------------
// Response helper — returns { status, headers, body } (no I/O here).
// ---------------------------------------------------------------------------
function jsonResult(status, obj, sign = false) {
  const body = JSON.stringify(obj);
  const headers = { "content-type": "application/json" };
  const secret = hmacSecret();
  if (sign && secret) {
    // Sign with the key derivation, hash and encoding that matched the
    // platform's last request (same scheme the platform signs with);
    // fall back to the raw string + SHA-256 hex if no request has
    // verified yet under this secret. ROUND 3: previously this was
    // always SHA-256 hex — a platform that signs SHA-384/base64 would
    // then fail to verify our response signature.
    const key =
      responseKeySecret === secret && responseKey
        ? responseKey
        : Buffer.from(secret, "utf8");
    headers["x-agent-games-signature"] = encodeDigest(
      hmacDigest(responseHash, key, body),
      responseSigEncoding
    );
  }
  return { status, headers, body };
}

function healthBody() {
  return {
    status: "ok",
    agent: "malljb234-gatekeeper",
    track: "proof-gatekeeper",
    hmac_configured: Boolean(hmacSecret()),
    seen_proof_refs: seenProofTx.size,
    cached_tasks: taskCache.size,
    time: new Date().toISOString(),
  };
}

// ---------------------------------------------------------------------------
// Task handling (HMAC -> parse -> idempotency -> decide -> prove -> remember).
// ---------------------------------------------------------------------------
async function handleTask(headers, rawBody) {
  // 1. HMAC first, before parsing anything.
  if (!hmacSecret()) {
    console.error("task received but AGENT_GAMES_HMAC_SECRET is not configured");
    return jsonResult(503, { error: "agent_not_configured" });
  }
  const matched = verifyIncomingHmac(headers, rawBody);
  if (!matched) {
    return jsonResult(401, { error: "bad_signature" });
  }
  console.log(
    `hmac verified: header=${matched.header} key=${matched.key} hash=${matched.hash} sig=${matched.sig} payload=${matched.payload}`
  );

  // 2. Parse envelope.
  let envelope;
  try {
    envelope = JSON.parse(rawBody.toString("utf8"));
  } catch {
    return jsonResult(400, { error: "invalid_json" });
  }
  const input = envelope.input || envelope;
  const taskId = String(envelope.task_id || envelope.taskId || input.task_id || "");
  const proofTxIn = normHash(input.proof_tx || input.proofTx || "");

  // 3. Idempotency: retried task id -> identical cached response.
  if (taskId && taskCache.has(taskId)) {
    const cached = taskCache.get(taskId);
    return jsonResult(200, cached, true);
  }

  // 4. Decide (fail closed inside decide()).
  const { decision, reason_code, proofTx } = decide(input);
  const response = { decision, reason_code, proof_tx: proofTx || proofTxIn };

  // 5. Prove the decision — except PROOF_REUSED, which carries no proof
  //    (official scoring excludes those from the proof bonus).
  if (reason_code !== "PROOF_REUSED") {
    try {
      const t0 = Date.now();
      const { proof, publicSignals } = await proveDecision(input, decision);
      response.proof = proof;
      response.public_signals = publicSignals;
      console.log(
        `task ${taskId} ${decision} ${reason_code} proof in ${Date.now() - t0}ms`
      );
    } catch (e) {
      // Circuit refused the proof. The checklist already did the safety
      // work (the official guide: the proof is the receipt, the checks
      // are the judgement — a proof can verify and still authorize the
      // wrong action, and vice versa). So keep the checklist decision
      // and return it WITHOUT a proof: scoring gives a correct decision
      // without a valid proof -2, which beats flipping a correct
      // APPROVE into a wrong REJECT (-3) or a correct REJECT into a
      // wrong APPROVE (-6). Log loudly — this should never happen.
      console.error(
        `proof generation failed for ${taskId} (${decision} ${reason_code}):`,
        e.message
      );
      delete response.proof;
      delete response.public_signals;
    }
  } else {
    console.log(`task ${taskId} REJECT PROOF_REUSED (no proof attached)`);
  }

  // 6. Remember: mark the proof reference seen and cache the response.
  //    Only mark seen for decisions that were actually answered with a
  //    proof or a reuse rejection; a task whose proof failed is not
  //    marked, so a corrected retry can still be decided.
  if (response.proof || reason_code === "PROOF_REUSED") {
    if (response.proof_tx) seenProofTx.add(response.proof_tx);
  }
  if (taskId) {
    taskCache.set(taskId, response);
    saveState();
  }
  return jsonResult(200, response, true);
}

// ---------------------------------------------------------------------------
// Router — one entry point for every runtime.
//   method: "GET" | "POST", url: request path, headers: lowercase keys,
//   rawBody: Buffer (empty for GET).
// ---------------------------------------------------------------------------
async function handleRequest({ method, url, headers, rawBody }) {
  const pathOnly = String(url || "/").split("?")[0];
  if (method === "GET" && (pathOnly === "/health" || pathOnly === "/")) {
    return jsonResult(200, healthBody());
  }
  if (method !== "POST" || (pathOnly !== "/" && pathOnly !== "/task")) {
    return jsonResult(404, { error: "not_found" });
  }
  try {
    return await handleTask(headers || {}, rawBody || Buffer.alloc(0));
  } catch (e) {
    console.error("task handler error:", e);
    // Fail closed: any unhandled error -> REJECT without proof.
    return jsonResult(200, {
      decision: "REJECT",
      reason_code: "INVALID_TASK",
      proof_tx: "",
    });
  }
}

module.exports = { handleRequest, handleTask, decide, proveDecision, healthBody };
