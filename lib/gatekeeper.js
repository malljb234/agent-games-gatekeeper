/**
 * malljb234-gatekeeper — shared core for the Proof Gatekeeper agent.
 *
 * Used by BOTH:
 *   - server.js            (plain Node.js HTTP server: Render, local, any VPS)
 *   - api/index.js         (Vercel serverless function, Hobby plan)
 *
 * The logic is identical on both runtimes; only the HTTP plumbing differs.
 * Keeping one core means the locally-tested behaviour (test/test-local.js)
 * is exactly what runs in production.
 *
 * Flow (official builder field guide + Proof Gatekeeper event page):
 *   1. Platform POSTs a signed task envelope (HTTPS, 60s window).
 *   2. Verify the HMAC signature on the RAW body before parsing anything.
 *      Bad signature -> 401, no further work.
 *   3. Decide deterministically over the task fields (fixed checklist):
 *      VK match, balance >= minimum, not expired, recipient match,
 *      amount <= cap, proof reference not seen before.
 *      One mismatch -> REJECT. All pass -> APPROVE.
 *   4. Generate a Groth16 proof of that decision with snarkjs + the
 *      tournament's own gatekeeper circuit (BN254, Circom 2.x) and return
 *      the proof + public signals in the signed response.
 *   5. Fail closed: any error / timeout / uncertainty -> REJECT.
 *   6. Remember: task IDs + proof references are persisted, so a
 *      re-submitted proof is rejected and a retried task returns the
 *      identical cached response.
 *
 * Environment:
 *   AGENT_GAMES_HMAC_SECRET  per-agent secret from the Agent Games
 *                              dashboard ("Rotate Secret"). REQUIRED for
 *                              serving tasks; without it the endpoint
 *                              answers /health only and 503s tasks.
 *   REGISTERED_VK_HASH       default = official gatekeeper vkHash from
 *                              https://agentgames.zkverify.io/api/circuit-info
 *                              (0x6b79c6012a6d8651f3e13bc4d2a20370280ab49700c90c5316d4168bfbad77b0)
 *   STATE_PATH               where to persist seen proof refs + task cache.
 *                              Default: <repo-root>/state.json. On Vercel
 *                              the filesystem is read-only except /tmp, so
 *                              api/index.js sets STATE_PATH=/tmp/... and
 *                              persistence is best-effort (in-memory state
 *                              survives only while the instance is warm).
 *
 * Assumptions that can only be confirmed by the dashboard preflight /
 * practice tasks (documented, not guessed-away):
 *   - Response carries decision, reason_code, proof_tx plus, for provable
 *     decisions, the snarkjs `proof` object and `public_signals` array.
 *   - `taskId` circuit signal = first 31 bytes of sha256(task_id) as a
 *     field element; `salt` = first 31 bytes of HMAC(secret, task_id).
 *
 * Incoming HMAC — what the official docs pin down (agentgames.zkverify.io
 * /rules §1.3 and /build, read 2026-11-15):
 *   - header: `x-agent-games-signature`
 *   - HMAC over the raw request body
 *   - secret: 32 random bytes, generated by the platform, shown once
 * What they do NOT pin down:
 *   - how the 32 bytes are DISPLAYED (hex? base64? base64url?) — and
 *     therefore which bytes the platform actually signs with: the raw 32
 *     bytes, or the displayed string as UTF-8
 *   - the signature encoding (hex? base64? `sha256=` prefix?)
 *   - whether a timestamp is mixed into the signed payload (the build
 *     guide says "the task signature and timestamp are valid", which
 *     suggests a timestamp may be part of the scheme)
 * Observed 2026-11-15: 7 preflight attempts, secret rotated 3x with a
 * redeploy each time, 401 every time — so the platform's key is NOT the
 * displayed string used as UTF-8 bytes. Most likely mismatch: the
 * platform signs with the 32 raw bytes while the dashboard shows them
 * hex/base64-encoded. verifyIncomingHmac() below therefore tries every
 * plausible (key, signature-encoding, payload) combination and accepts
 * if ANY matches; on a match it logs WHICH variant matched (labels only,
 * never values) so the Netlify logs reveal the platform's real scheme.
 * Every candidate still requires knowledge of the secret itself, so this
 * does not weaken authentication. Fail-closed is preserved: no match
 * -> 401, no work done.
 *
 * ROUND 2 (2026-11-15 ~14:38 WIB) — the round-1 fix is live on Netlify
 * (repo 30 commits, deployed 14:36 WIB) and the signed preflight STILL
 * 401s. The function log (14:37:28 WIB, req 918fec74) says:
 *   "hmac mismatch: sig_header=x-agent-games-signature, sig_len=64,
 *    sig_formats=[hex, base64], body_len=171,
 *    tried_keys=[raw-string, base64-decoded], tried_payloads=[raw-body]"
 * Findings from that line:
 *   - The signature is 64 chars -> hex-encoded 32-byte HMAC (base64 of
 *     32 bytes would be 44 chars). Header name confirmed.
 *   - "hex-decoded" was NOT tried. That is NOT a pruning bug:
 *     decodeHexLoose returns null only for non-hex input, and the secret
 *     DID decode as base64 (length % 4 === 0, base64 alphabet) — so the
 *     secret string contains a non-hex character: it is base64, not hex.
 *     "base64url-decoded" was correctly deduped (no -/_ in the secret,
 *     so it decodes identically to base64).
 *   - REAL pruning bug found in decodeBase64Loose: it rejected any
 *     input whose length % 4 !== 0. A 32-byte secret as UNPADDED
 *     base64url is 43 chars and was silently dropped. Fixed: pad with
 *     '=' before decoding (a length % 4 === 1 input is still rejected
 *     as invalid base64). Same fix on the signature side.
 *   - No timestamp header was present, so no timestamp payload was
 *     tried — but /build says "the task signature and timestamp are
 *     valid", so the timestamp may live INSIDE the envelope body.
 *     candidatePayloads now also reads timestamp fields from the body.
 *   - Since raw-string AND base64-decoded keys both failed against the
 *     raw body, the signed content is probably NOT the raw body. Round 2
 *     adds payload families: canonical JSON (sorted keys), re-stringified
 *     JSON, pretty JSON, canonical JSON of the `input` object only,
 *     HMAC over sha256(body) (hex + raw), body with trailing newline
 *     stripped/added, method+path+body and path+body (request-line
 *     style), agent-id prefix/suffix ("malljb234-gatekeeper" and the
 *     owner handle "malljb238"), endpoint-URL prefix, and body-timestamp
 *     variants. Plus two more key derivations: sha256 of the displayed
 *     secret string, and sha256 of the decoded key bytes.
 *   - On mismatch the log now ALSO prints the raw request body (a
 *     171-byte health ping has no secret material; capped at 2000 chars)
 *     so the next preflight reveals the envelope's real fields. NEVER
 *     log the secret, the received signature value, or any computed
 *     HMAC/key bytes — labels and the body only.
 */

